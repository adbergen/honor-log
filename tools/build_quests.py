#!/usr/bin/env python3
"""Build Data/Quests.lua from tools/quests_source.json.

The source is a curated list of the PvP quest ids the game data names (one object per id: bg, faction, level,
kind, week for the season's weekly quests, and the English name kept only as a fallback for a client that has
no title). No quest text is copied. Standard library only, no network.

Usage:  python3 tools/build_quests.py [--report] [--check]
  --report  print the counts by battleground, faction and kind
  --check   exit non-zero when Data/Quests.lua is not what this tool would write
"""

import argparse
import json
import pathlib
import sys
from collections import Counter

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "tools" / "quests_source.json"
OUT = ROOT / "Data" / "Quests.lua"

BGS = ["AV", "WSG", "AB", "DI", "ALL", "SEASON"]
FACTIONS = ["Horde", "Alliance"]
KINDS = ["offer", "repeat", "weekly"]
FIELDS = ["bg", "faction", "level", "kind", "week", "name"]

HEADER = """-- HonorLog quest list
-- GENERATED by tools/build_quests.py from tools/quests_source.json. Do not edit by hand.
-- The PvP quest ids the game data names (Wowhead Forever tooltips and the client's QuestV2 / QuestLine tables,
-- build 1.60.1.71037), by battleground and faction. The names are an English fallback only: the client's own
-- title is shown when it has one. No quest text is kept here.
--
-- bg: AV, WSG, AB, DI, ALL (the quests of all four battlegrounds) or SEASON (the season's own and the weekly
-- quests). faction: Horde or Alliance, absent when both can take it. kind: offer (has an objective), repeat
-- (the repeatable hand-in version) or weekly (week 1 to 10).

local _, HonorLog = ...
HonorLog = HonorLog or {}

"""


def lua_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def load():
    rows = json.loads(SOURCE.read_text(encoding="utf-8"))
    seen = set()
    for r in rows:
        i = r["id"]
        if i in seen:
            sys.exit("duplicate id %d" % i)
        seen.add(i)
        if r["bg"] not in BGS or r["kind"] not in KINDS:
            sys.exit("id %d: unknown bg or kind" % i)
        if r.get("faction") not in (None, *FACTIONS):
            sys.exit("id %d: unknown faction" % i)
        if (r["kind"] == "weekly") != ("week" in r):
            sys.exit("id %d: week belongs to weekly quests only" % i)
        extra = set(r) - set(FIELDS) - {"id"}
        if extra:
            sys.exit("id %d: unknown fields %s" % (i, sorted(extra)))
    return sorted(rows, key=lambda r: r["id"])


def render(rows):
    out = [HEADER, "HonorLog.QuestDB = {\n"]
    for r in rows:
        parts = []
        for f in FIELDS:
            if f in r:
                v = r[f]
                parts.append("%s = %s" % (f, lua_string(v) if isinstance(v, str) else v))
        out.append("    [%d] = { %s },\n" % (r["id"], ", ".join(parts)))
    out.append("}\n")
    return "".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--report", action="store_true")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    rows = load()
    text = render(rows)
    if args.check:
        have = OUT.read_text(encoding="utf-8") if OUT.exists() else None
        if have != text:
            print("Data/Quests.lua is not what tools/build_quests.py writes")
            return 1
        print("Data/Quests.lua is up to date (%d quests)" % len(rows))
    else:
        OUT.write_text(text, encoding="utf-8")
        print("wrote %s (%d quests)" % (OUT.relative_to(ROOT), len(rows)))
    if args.report:
        print("by battleground:", ", ".join("%s %d" % (b, n) for b, n in sorted(Counter(r["bg"] for r in rows).items(), key=lambda kv: BGS.index(kv[0]))))
        print("by faction:", ", ".join("%s %d" % (f, n) for f, n in sorted(Counter(r.get("faction", "none") for r in rows).items())))
        print("by kind:", ", ".join("%s %d" % (k, n) for k, n in sorted(Counter(r["kind"] for r in rows).items())))
        print("with a level: %d, without: %d" % (sum("level" in r for r in rows), sum("level" not in r for r in rows)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
